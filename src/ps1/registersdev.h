#pragma once

#include "ps1/registers.h"

/* DTL-H2000/H2700 host I/O and IRQ10 controller */

typedef enum {
	DTLH_IRQ_HOST     = 0,
	DTLH_IRQ_PIO      = 1,
	DTLH_IRQ_TTY_HOST = 4,
	DTLH_IRQ_TTY_RX   = 5
} ATCONSIRQChannel;

typedef enum {
	DTLH_STAT_DATA_RX_NOT_EMPTY = 1 << 0,
	DTLH_STAT_DATA_TX_NOT_FULL  = 1 << 2,
	DTLH_STAT_TTY_TX_NOT_FULL   = 1 << 3,
	DTLH_STAT_TTY_RX_NOT_EMPTY  = 1 << 4
} ATCONSStatusFlag;

#define DTLH_STAT     _MMIO8 (DEV8_BASE | 0x00)
#define DTLH_TTY      _MMIO8 (DEV8_BASE | 0x02)
#define DTLH_DATA     _MMIO16(DEV8_BASE | 0x04)
#define DTLH_IRQ_STAT _MMIO8 (DEV8_BASE | 0x30)
#define DTLH_IRQ_MASK _MMIO8 (DEV8_BASE | 0x32)

/* no$psx emulator API */

typedef enum {
	NOCASH_TURBO_CDROM       = 1 << 0,
	NOCASH_TURBO_MEMORY_CARD = 1 << 1,
	NOCASH_TURBO_CONTROLLER  = 1 << 2
} NocashTurboFlag;

#define NOCASH_MAGIC  _MMIO32(DEV8_BASE | 0x60)
#define NOCASH_ENABLE _MMIO16(DEV8_BASE | 0x64)
#define NOCASH_HALT   _MMIO8 (DEV8_BASE | 0x66)
#define NOCASH_TURBO  _MMIO8 (DEV8_BASE | 0x67)

/* PCSX-Redux emulator API */

#define PCSX_MAGIC        _MMIO32(DEV8_BASE | 0x80) // Read
#define PCSX_PUTC         _MMIO8 (DEV8_BASE | 0x80) // Write
#define PCSX_EXEC_SLOT    _MMIO8 (DEV8_BASE | 0x81) // Write
#define PCSX_EXIT         _MMIO16(DEV8_BASE | 0x82) // Write
#define PCSX_MESSAGE      _MMIO32(DEV8_BASE | 0x84)
#define PCSX_KERNEL_CHECK _MMIO8 (DEV8_BASE | 0x88)

/* DTL-T10000/T15000 (PS2) PIF host I/O */

#define DTLT_PIF_BID  _MMIO16(DEV8_BASE | 0x1800)
#define DTLT_PIF_RST  _MMIO16(DEV8_BASE | 0x1804)
#define DTLT_PIF_CPR  _MMIO16(DEV8_BASE | 0x1808)
#define DTLT_PIF_CPS  _MMIO16(DEV8_BASE | 0x180c)
#define DTLT_PIF_FST  _MMIO16(DEV8_BASE | 0x1810)
#define DTLT_PIF_TXC  _MMIO16(DEV8_BASE | 0x1814)
#define DTLT_PIF_RXC  _MMIO16(DEV8_BASE | 0x1818)
#define DTLT_PIF_F1C  _MMIO16(DEV8_BASE | 0x181c)
#define DTLT_PIF_IST  _MMIO16(DEV8_BASE | 0x1820)
#define DTLT_PIF_ISP  _MMIO16(DEV8_BASE | 0x1824)
#define DTLT_PIF_IER  _MMIO16(DEV8_BASE | 0x1828)
#define DTLT_PIF_CSI  _MMIO16(DEV8_BASE | 0x182c)
#define DTLT_PIF_FSI  _MMIO16(DEV8_BASE | 0x1830)
#define DTLT_PIF_AEO  _MMIO16(DEV8_BASE | 0x1834)
#define DTLT_PIF_AFO  _MMIO16(DEV8_BASE | 0x1838)
#define DTLT_PIF_BCR  _MMIO16(DEV8_BASE | 0x183c)
#define DTLT_PIF_DATA _MMIO32(DEV8_BASE | 0x1840)

/* PS2 Deckard IOP emulator API */

